// Builds seed/seed.sql from seed/categories.json and seed/posts/*.md.
//
// Each post file starts with a frontmatter block of `key: <JSON value>` lines.
// Inserts are idempotent (existing slugs are left untouched), so the seed can be
// re-applied to a database that already has edits made through /admin/.
//
//   node scripts/build-seed.mjs

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const seedDir = path.join(root, 'seed')
const sql = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)

function parsePost(file) {
  const raw = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n')
  const m = raw.match(/^---\n([\s\S]*?)\n---\n\n?([\s\S]*)$/)
  if (!m) throw new Error(`${file}: missing frontmatter`)
  const meta = {}
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i < 1) throw new Error(`${file}: bad frontmatter line "${line}"`)
    meta[line.slice(0, i).trim()] = JSON.parse(line.slice(i + 1).trim())
  }
  for (const k of ['title', 'slug', 'category', 'publishedAt', 'readingMinutes', 'excerpt']) {
    if (meta[k] === undefined) throw new Error(`${file}: missing "${k}"`)
  }
  return { ...meta, body: m[2].trim() + '\n' }
}

const categories = JSON.parse(fs.readFileSync(path.join(seedDir, 'categories.json'), 'utf8'))
const posts = fs
  .readdirSync(path.join(seedDir, 'posts'))
  .filter((f) => f.endsWith('.md'))
  .map((f) => parsePost(path.join(seedDir, 'posts', f)))
  // Oldest first so newer posts get higher ids; same-day ties are broken by id DESC
  // when listing, matching the original site's ordering.
  .sort((a, b) => a.publishedAt.localeCompare(b.publishedAt) || b.slug.localeCompare(a.slug))

const known = new Set(categories.map((c) => c.slug))
for (const p of posts) if (!known.has(p.category)) throw new Error(`${p.slug}: unknown category ${p.category}`)

const out = ['-- Generated by scripts/build-seed.mjs – do not edit by hand.', '']
categories.forEach((c, i) => {
  out.push(
    `INSERT INTO categories (slug, label, sort_order) VALUES (${sql(c.slug)}, ${sql(c.label)}, ${i}) ` +
      `ON CONFLICT(slug) DO UPDATE SET label = excluded.label, sort_order = excluded.sort_order;`,
  )
})
out.push('')
for (const p of posts) {
  out.push(
    'INSERT INTO posts (slug, title, excerpt, seo_title, category_slug, cover_url, cover_alt, og_image_url, body_md, reading_minutes, published_at, status) VALUES (' +
      [p.slug, p.title, p.excerpt, p.seoTitle ?? null, p.category, p.coverUrl ?? null, p.coverAlt ?? '', p.ogImageUrl ?? null, p.body, p.readingMinutes, p.publishedAt, p.status ?? 'published']
        .map(sql)
        .join(', ') +
      ') ON CONFLICT(slug) DO NOTHING;',
  )
}
fs.writeFileSync(path.join(seedDir, 'seed.sql'), out.join('\n') + '\n')
console.log(`seed/seed.sql: ${categories.length} categories, ${posts.length} posts`)
